// Saves one real search from your deployed Worker as site/demo-report.js, for the landing-page demo.
// Run once from the repo root (needs internet):  node tools/save-demo.mjs
// Uses one ordinary search (or none if it is cached). No AI, no keys.
import { writeFileSync } from "node:fs";
import "../site/search-presets.js";

const WORKER = "https://topic-momentum-meter.michelegambino24.workers.dev";
const children = globalThis.TMM_SEARCH_PRESETS.children.terms;
// Same Middle East country coverage used by the report's regional suggestions.
const authored = ["AE", "BH", "EG", "IL", "IQ", "IR", "JO", "KW", "LB", "OM", "PS", "QA", "SA", "SY", "TR", "YE"];
const search = { q: "mental health", include: children.join(","), authored: authored.join(",") };
const question = "Is children’s mental health a growing field in the Middle East, and who’s leading it?";

const url = new URL(WORKER + "/api/topic");
for (const [key, value] of Object.entries(search)) url.searchParams.set(key, value);
const response = await fetch(url);
if (!response.ok) throw new Error(`The Worker answered HTTP ${response.status}. Check the Worker is deployed and try again.`);
const report = await response.json();
if (!report?.kpis?.total) throw new Error("The demo search found no papers. Choose another demo search in tools/save-demo.mjs.");

const number = (value) => new Intl.NumberFormat("en-US").format(value);
const percent = (value) => `${value < 0 ? "−" : "+"}${Math.abs(value * 100).toFixed(Math.abs(value * 100) >= 10 ? 0 : 1)}%`;
const year = Number(report.updated.slice(0, 4));
const lastComplete = year - 1;
const growth = Object.hasOwn(report.kpis, "growth") ? report.kpis.growth : report.kpis.growth5y;
const expert = (report.experts || []).find((item) => String(item.name || "").trim());
const country = (report.countries || []).filter(item => authored.includes(item.code) && item.count > 0).sort((a, b) => b.count - a.count)[0];
if (!expert || !country || !Number.isFinite(growth) || report.years.filter(item => item.year < year && item.count > 0).length < 5) throw new Error("The regional demo needs more yearly counts, country evidence or expert rankings. The saved demo has not been changed.");

const insights = [];
if (Number.isFinite(growth)) insights.push({ label: "Momentum", text: `${report.kpis.momentum || "Growing"}: ${percent(growth)} a year (${report.kpis.growthLabel || "5-year growth"})` });
if (country) insights.push({ label: "Leading country", text: `${country.name || country.code}: ${number(country.count)} papers with an affiliated author` });
if (expert) insights.push({ label: "Expert to invite", text: `${expert.name}, ${number(expert.count)} papers on this topic` });

const demo = {
  question,
  chips: ["Topic: mental health", "About: Children 0–9", "Author affiliation: Middle East"],
  title: "Children’s mental health in the Middle East",
  from: report.from ?? 2010,
  partialYear: year,
  years: report.years.filter((item) => item.year >= (report.from ?? 2010)),
  fetched: report.updated,
  kpis: { total: report.kpis.total, lastYear: report.kpis.lastYear, lastYearLabel: `Papers in ${lastComplete}`, growth: Number.isFinite(growth) ? growth : null, growthLabel: report.kpis.growthLabel || "Growth" },
  countries: (report.countries || []).filter((item) => item.code && Number.isFinite(item.count) && item.count > 0).sort((a, b) => b.count - a.count).slice(0, 8).map(({ code, count }) => ({ code, count })),
  experts: (report.experts || []).filter((item) => item.name && Number.isFinite(item.count) && item.count > 0).sort((a, b) => b.count - a.count).slice(0, 8).map(({ name, count }) => ({ name, count })),
  insights,
  open: "app.html#" + new URLSearchParams({ topic: search.q, include: search.include, authored: search.authored }).toString()
};

const header = `// Generated by tools/save-demo.mjs from the live Worker on ${report.updated}. Real OpenAlex counts; do not edit by hand.\n`;
writeFileSync(new URL("../site/demo-report.js", import.meta.url), header + "window.TMM_DEMO = " + JSON.stringify(demo, null, 2) + ";\n");
console.log(`Wrote site/demo-report.js: ${number(report.kpis.total)} papers, ${insights.length} insights.`);
