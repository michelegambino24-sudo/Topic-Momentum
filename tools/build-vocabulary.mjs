// Builds site/vocabulary.js: a list of real research words used for "Did you mean…?" suggestions.
// Run once from the repo root (it needs internet):  node tools/build-vocabulary.mjs
// Source: OpenAlex topics and keywords (free, open data). No other service is used.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const key = process.env.OPENALEX_KEY || (() => {
  // Optional: reuse the local Worker key if it exists; the script also works without a key.
  const file = new URL("../worker/.dev.vars", import.meta.url);
  if (!existsSync(file)) return "";
  const match = readFileSync(file, "utf8").match(/^OPENALEX_KEY\s*=\s*"?([^"\r\n]+)"?/m);
  return match ? match[1].trim() : "";
})();

const STOP = new Set("about above after again against also among and any are because been before being below between both but can could did does doing down during each else ever every for from further had has have having her here hers him his how into its itself just may might more most much must new not now off once only other our ours out over own same shall she should some such than that the their theirs them then there these they this those through too under until upon very was were what when where which while who whom why will with within without would you your using used based study studies analysis role effect effects impact".split(" "));

async function pages(entity, select, { limit = Infinity, sort = "" } = {}) {
  const items = [];
  let cursor = "*";
  for (let page = 1; cursor && items.length < limit; page++) {
    const url = new URL(`https://api.openalex.org/${entity}`);
    url.searchParams.set("per-page", "200");
    url.searchParams.set("cursor", cursor);
    url.searchParams.set("select", select);
    if (sort) url.searchParams.set("sort", sort);
    if (key) url.searchParams.set("api_key", key);
    let data;
    for (let attempt = 1; ; attempt++) {
      const response = await fetch(url);
      if (response.ok) { data = await response.json(); break; }
      if (attempt >= 4) throw new Error(`OpenAlex ${entity} page ${page} failed with HTTP ${response.status}. Try again in a few minutes.`);
      await new Promise(resolve => setTimeout(resolve, 1500 * attempt));
    }
    items.push(...data.results);
    cursor = data.meta?.next_cursor || null;
    process.stdout.write(`\r${entity}: ${items.length} of ${data.meta?.count ?? "?"}   `);
    await new Promise(resolve => setTimeout(resolve, 150));
  }
  process.stdout.write("\n");
  return items;
}

const counts = new Map();
const add = text => {
  for (const raw of String(text || "").toLowerCase().match(/\p{L}[\p{L}'-]*/gu) || []) {
    for (const word of raw.split(/[-']/)) {
      if (word.length < 4 || word.length > 30 || STOP.has(word)) continue;
      counts.set(word, (counts.get(word) || 0) + 1);
    }
  }
};

const topics = await pages("topics", "display_name,keywords,description,subfield,field");
for (const topic of topics) {
  add(topic.display_name); add(topic.description);
  for (const keyword of topic.keywords || []) add(keyword);
  add(topic.subfield?.display_name); add(topic.field?.display_name);
}
// OpenAlex has about a million keywords; the 20,000 most used ones are plenty for spelling help.
const keywords = await pages("keywords", "display_name", { limit: 20000, sort: "works_count:desc" });
for (const keyword of keywords) add(keyword.display_name);

// Most frequent words first, so ties in a suggestion pick the more common word.
const words = [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([word]) => word);
const header = `// Generated by tools/build-vocabulary.mjs from OpenAlex topics and keywords on ${new Date().toISOString().slice(0, 10)}.\n// ${words.length} words, most frequent first. Do not edit by hand; run the script again to refresh.\n`;
writeFileSync(new URL("../site/vocabulary.js", import.meta.url), header + "globalThis.TMM_VOCABULARY = " + JSON.stringify(words.join(" ")) + ";\n");
console.log(`Wrote site/vocabulary.js with ${words.length} words.`);
